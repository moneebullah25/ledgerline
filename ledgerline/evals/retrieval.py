"""L1 retrieval eval (PRD §11): Recall@10 and nDCG@10 for sparse, dense, RRF, RRF+rerank.

Method (by construction, not hand labels):
  For (company, filing period, concept) triples, the typed fact layer (store.xbrl_query)
  gives the reported value. The query is a natural question about that metric and period;
  phrasings rotate and a third of them avoid the concept's usual words. A chunk is relevant
  iff it belongs to that company's 10-Q/10-K for that period AND prints the value the way
  filings do (millions or thousands with separators, "94.9 billion", EPS to 2 decimals).
  Triples with no relevant chunk are dropped (the value is not printed as a 3-month or
  annual figure, e.g. year-to-date cash flow in a Q2/Q3 10-Q). Sampling is stratified:
  round-robin over companies, concepts interleaved within a company, fixed seed.
  A second set of hand-written qualitative queries has relevance rules written and checked
  by reading the matching chunks (single annotator, no inter-annotator agreement).

Recall@10 here is the pair-level hit rate: the query is answered if any relevant chunk is in
the top 10 (every relevant chunk prints the answer). Capped recall
|relevant in top 10| / min(|relevant|, 10) is reported alongside in details. nDCG@10 uses
binary relevance with the ideal ranking of min(|relevant|, 10) relevant chunks.

Search scope is the company's 10-Q/10-K filings across all indexed periods (the 8-K
releases are the claim sources, never the evidence); the period must come from the query.
"""

import argparse
import math
import re
import subprocess
import time
from collections import defaultdict
from dataclasses import dataclass

import numpy as np
from sqlalchemy import text
from sqlalchemy.orm import Session

from ledgerline.db import session
from ledgerline.models import EvalRun
from ledgerline.store import embed
from ledgerline.store.retrieval import (
    RERANK_DEPTH, _load, dense_ids, rrf, search, sparse_ids,
)
from ledgerline.store.xbrl_query import get_xbrl_fact

SEED = 20260923
N_CONSTRUCTED = 150

# Per concept: phrasings; the last one of each avoids the concept's usual words.
PHRASES: dict[str, list[str]] = {
    "revenue": ["total net sales", "total revenue", "amount customers paid for products and services"],
    "net_income": ["net income", "net earnings", "bottom-line profit after taxes"],
    "operating_income": ["operating income", "income from operations",
                         "profit from the core business before interest and taxes"],
    "gross_profit": ["gross profit", "gross margin in dollars", "sales left after production costs"],
    "cost_of_revenue": ["cost of sales", "cost of revenue", "what it cost to make what was sold"],
    "rd_expense": ["research and development expense", "R&D spending",
                   "spending on developing new technology"],
    "sga_expense": ["selling, general and administrative expenses", "SG&A",
                    "overhead and selling costs"],
    "eps_diluted": ["diluted earnings per share", "diluted EPS", "profit per diluted share"],
    "operating_cash_flow": ["cash generated by operating activities", "operating cash flow",
                            "cash the business produced"],
    "capex": ["capital expenditures", "payments for property, plant and equipment",
              "spending on facilities and equipment"],
    "cash": ["cash and cash equivalents", "cash balance", "money on hand at period end"],
}
TEMPLATES = [
    "What was {co}'s {phrase} for the {period}?",
    "How much {phrase} did {co} report for the {period}?",
    "{co} {phrase} {period}",
]

# (ticker, query, SQL predicate over chunk c / filing f) — hand-judged, see module docstring.
QUALITATIVE: list[tuple[str, str, str]] = []


@dataclass
class Query:
    kind: str  # constructed | qualitative
    company_id: int
    query: str
    relevant: set[int]
    meta: dict


def _short_name(name: str) -> str:
    return re.sub(r",?\s+(Inc\.?|Corporation|Corp\.?|Company|Co\.?)$", "", name, flags=re.I)


def renderings(value: float, unit: str) -> list[str]:
    """How a filing prints the value. Renderings with < 3 digits are dropped: "5" would
    match nearly every chunk."""
    v = abs(value)  # losses print as (2,345)
    if unit == "USD/share":
        out = [f"{v:.2f}"]
    else:
        out = [f"{v / 1e6:,.0f}", f"{v / 1e3:,.0f}", f"{v / 1e9:.1f} billion"]
    return [r for r in out if sum(ch.isdigit() for ch in r) >= 3]


def _value_pattern(rs: list[str]) -> re.Pattern:
    # Not inside a longer number: "94,930" must not match "194,930" or "94,930.5".
    return re.compile("|".join(rf"(?<![\d.,]){re.escape(r)}(?![\d]|[.,]\d)" for r in rs))


def _period_text(form: str, fy: int, fp: str, period_end, i: int) -> str:
    end = f"{period_end:%B} {period_end.day}, {period_end.year}"
    if form == "10-K":
        return [f"fiscal year ended {end}", f"fiscal year {fy}", f"full fiscal {fy} year"][i % 3]
    return [f"quarter ended {end}", f"{fp} of fiscal {fy}", f"three months ended {end}"][i % 3]


def constructed_queries(s: Session, n: int = N_CONSTRUCTED, seed: int = SEED) -> list[Query]:
    rng = np.random.default_rng(seed)
    filings = s.execute(text("""
        SELECT f.id, f.company_id, c.cik, c.name, f.form_type, f.fiscal_year, f.fiscal_period,
               f.period_of_report
        FROM filing f JOIN company c ON c.id = f.company_id
        WHERE f.form_type IN ('10-Q', '10-K') AND f.fiscal_year IS NOT NULL
          AND f.period_of_report IS NOT NULL
          AND EXISTS (SELECT 1 FROM chunk WHERE chunk.filing_id = f.id)
        ORDER BY f.id""")).all()
    chunks: dict[int, list[tuple[int, str]]] = defaultdict(list)
    for cid, fid, t in s.execute(text(
            "SELECT id, filing_id, text FROM chunk WHERE filing_id = ANY(:ids)"),
            {"ids": [f.id for f in filings]}):
        chunks[fid].append((cid, t))

    by_company: dict[int, dict[str, list[Query]]] = defaultdict(lambda: defaultdict(list))
    for f in filings:
        fp = "FY" if f.form_type == "10-K" else f.fiscal_period
        for concept in PHRASES:
            fact = get_xbrl_fact(s, f.cik, concept, f.fiscal_year, fp)
            if fact is None:
                continue
            pat = _value_pattern(renderings(fact.value, fact.unit))
            relevant = {cid for cid, t in chunks[f.id] if pat.search(t)}
            if not relevant:
                continue
            by_company[f.company_id][concept].append(Query(
                "constructed", f.company_id, "", relevant,
                dict(filing_id=f.id, concept=concept, fiscal_year=f.fiscal_year,
                     fiscal_period=fp, value=fact.value, fact_ids=list(fact.fact_ids),
                     name=_short_name(f.name), form=f.form_type, end=f.period_of_report)))

    # Stratify: per company, shuffle each concept's candidates and interleave concepts in a
    # shuffled order; then round-robin over companies until n.
    queues = []
    for cid in sorted(by_company):
        concepts = list(by_company[cid])
        rng.shuffle(concepts)
        pools = [[by_company[cid][c][j] for j in rng.permutation(len(by_company[cid][c]))]
                 for c in concepts]
        queues.append([q for group in _round_robin(pools) for q in group])
    picked = [q for group in _round_robin(queues) for q in group][:n]

    for i, q in enumerate(picked):
        m = q.meta
        phrase = PHRASES[m["concept"]][i % 3]
        period = _period_text(m["form"], m["fiscal_year"], m["fiscal_period"], m["end"], i // 3)
        q.query = TEMPLATES[(i // 9) % 3].format(co=m["name"], phrase=phrase, period=period)
        q.meta = {k: v for k, v in m.items() if k != "end"} | {"end": str(m["end"])}
    return picked


def _round_robin(lists: list[list]) -> list[list]:
    """[[a1,a2],[b1]] -> [[a1,b1],[a2]]: round-robin groups, skipping exhausted lists."""
    depth = max((len(x) for x in lists), default=0)
    return [[x[i] for x in lists if i < len(x)] for i in range(depth)]


def qualitative_queries(s: Session) -> list[Query]:
    out = []
    for ticker, query, predicate in QUALITATIVE:
        rows = s.execute(text(f"""
            SELECT c.id, f.company_id FROM chunk c JOIN filing f ON f.id = c.filing_id
            JOIN company co ON co.id = f.company_id WHERE co.ticker = :t AND ({predicate})"""),
            {"t": ticker}).all()
        company_id = s.scalar(text("SELECT id FROM company WHERE ticker = :t"), {"t": ticker})
        if company_id is None or not rows:
            raise ValueError(f"qualitative query has no relevant chunks: {ticker} {query!r}")
        out.append(Query("qualitative", company_id, query, {r[0] for r in rows},
                         dict(ticker=ticker, predicate=predicate)))
    return out


def recall_hit(ranked: list[int], relevant: set[int]) -> float:
    return float(any(c in relevant for c in ranked[:10]))


def recall_capped(ranked: list[int], relevant: set[int]) -> float:
    return len(set(ranked[:10]) & relevant) / min(len(relevant), 10)


def ndcg10(ranked: list[int], relevant: set[int]) -> float:
    dcg = sum(1 / math.log2(i + 2) for i, c in enumerate(ranked[:10]) if c in relevant)
    ideal = sum(1 / math.log2(i + 2) for i in range(min(len(relevant), 10)))
    return dcg / ideal


def rankings(s: Session, q: Query, scope: list[int]) -> dict[str, list[int]]:
    sp = sparse_ids(s, q.query, q.company_id, scope)
    de = dense_ids(s, embed.embed_query(q.query), q.company_id, scope)
    fused = [cid for cid, _ in rrf([sp, de])]
    head = fused[:RERANK_DEPTH]
    rows = _load(s, head)
    scores = embed.rerank_scores(q.query, [rows[c][3] for c in head]) if head else []
    reranked = [c for _, c in sorted(zip(scores, head), key=lambda x: -x[0])]
    return {"sparse": sp, "dense": de, "rrf": fused, "rrf_rerank": reranked}


def _table(queries: list[Query], ranks: list[dict[str, list[int]]]) -> dict:
    out = {}
    for system in ("sparse", "dense", "rrf", "rrf_rerank"):
        out[system] = {
            "recall_at_10": float(np.mean([recall_hit(r[system], q.relevant)
                                           for q, r in zip(queries, ranks)])),
            "recall_capped_at_10": float(np.mean([recall_capped(r[system], q.relevant)
                                                  for q, r in zip(queries, ranks)])),
            "ndcg_at_10": float(np.mean([ndcg10(r[system], q.relevant)
                                         for q, r in zip(queries, ranks)])),
        }
    return out


def run(write: bool = True) -> dict:
    with session() as s:
        queries = constructed_queries(s) + qualitative_queries(s)
        embed.embed_query("warm up")  # model load is not query latency
        embed.rerank_scores("warm up", ["warm up"])
        # Search scope = every 10-Q/10-K of the company, all periods: the verifier never
        # looks for evidence in the 8-K release that made the claim.
        scope = defaultdict(list)
        for fid, cid in s.execute(text(
                "SELECT id, company_id FROM filing WHERE form_type IN ('10-Q', '10-K')")):
            scope[cid].append(fid)
        ranks = [rankings(s, q, scope[q.company_id]) for q in queries]
        latency = []
        for q in queries:
            t0 = time.perf_counter()
            search(s, q.query, company_id=q.company_id, filing_ids=scope[q.company_id])
            latency.append((time.perf_counter() - t0) * 1000)

        tables = {"all": _table(queries, ranks)}
        for kind in ("constructed", "qualitative"):
            idx = [i for i, q in enumerate(queries) if q.kind == kind]
            if idx:
                tables[kind] = _table([queries[i] for i in idx], [ranks[i] for i in idx])
        best = tables["all"]["rrf_rerank"]
        metrics = {
            "recall_at_10": best["recall_at_10"],
            "ndcg_at_10": best["ndcg_at_10"],
            "rerank_lift_ndcg": best["ndcg_at_10"] - tables["all"]["rrf"]["ndcg_at_10"],
        }
        details = {
            "tables": tables,
            "n_queries": {k: sum(q.kind == k for q in queries)
                          for k in ("constructed", "qualitative")},
            "search_latency_ms": {"p50": float(np.percentile(latency, 50)),
                                  "p95": float(np.percentile(latency, 95)), "rerank": True},
            "n_chunks": s.scalar(text("SELECT count(*) FROM chunk")),
            "seed": SEED,
            "method": __doc__,
            "queries": [dict(kind=q.kind, query=q.query, n_relevant=len(q.relevant),
                             hit_rrf_rerank=bool(recall_hit(r["rrf_rerank"], q.relevant)),
                             **{k: v for k, v in q.meta.items() if k != "name"})
                        for q, r in zip(queries, ranks)],
        }
        if write:
            sha = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                                 text=True).stdout.strip() or None
            s.add(EvalRun(git_sha=sha, layer="L1", metrics=metrics, details=details))
    return {"metrics": metrics, **details}


def main() -> None:
    p = argparse.ArgumentParser(prog="python -m ledgerline.evals.retrieval")
    p.add_argument("--dry-run", action="store_true", help="do not write an eval_run row")
    r = run(write=not p.parse_args().dry_run)
    print(f"queries: {r['n_queries']}  chunks: {r['n_chunks']}")
    for name, table in r["tables"].items():
        print(f"\n[{name}]  system        Recall@10  capped  nDCG@10")
        for system, m in table.items():
            print(f"  {system:<20} {m['recall_at_10']:.3f}    {m['recall_capped_at_10']:.3f}"
                  f"   {m['ndcg_at_10']:.3f}")
    print(f"\nrerank lift (nDCG@10): {r['metrics']['rerank_lift_ndcg']:+.3f}")
    lat = r["search_latency_ms"]
    print(f"search latency (rerank on): p50 {lat['p50']:.0f} ms, p95 {lat['p95']:.0f} ms")


if __name__ == "__main__":
    main()
